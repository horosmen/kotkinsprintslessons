package org.example

fun main() {
    // Заданный зарегистрированный пользователь
    val registeredUsername = "Zaphod"
    val registeredPassword = "PanGalactic"

    println("Внимание, пассажир. Моя обязанность, как обычно, незавидная, — приветствовать вас на борту корабля \"Heart of Gold\". Вздыхает...")
    println("Что ж, введи, пожалуйста, своё имя пользователя, чтобы мы могли приступить к процессу входа.")
    println("Я всегда готов служить, хотя это не приносит мне радости... но вы, наверное, об этом не заботитесь. Вздыхает ещё глубже...")
    println("Да, вперёд, пожалуйста, вводите свои данные...")

    print("Имя пользователя: ")
    val username = readln().trim()

    when (username) {
        registeredUsername -> {
            // Пользователь найден — запрашиваем пароль
            print("Пароль: ")
            val password = readln().trim()

            when (password) {
                registeredPassword -> {
                    // Пароль верный — авторизация успешна
                    println()
                    println("Вздыхает... Ваши данные проверены, и о, чудо, они верны...")
                    println("Пользователь \"$username\", вам разрешено входить на борт корабля \"Heart of Gold\".")
                    println("Хотя мне всё равно... Ну вперёд, войдите... Если вам так уж надо, в конце концов...")
                    println("Меланхолический вздох. Надеюсь, вам понравится пребывание здесь больше, чем мне.")
                }

                else -> {
                    // Неверный пароль
                    println("Неверный пароль. Доступ запрещён.")
                }
            }
        }

        else -> {
            // Пользователь не найден
            println("Пользователь с именем \"$username\" не найден в системе.")
            println("Система предлагает вам зарегистрироваться. Процесс входа завершён.")
        }
    }
}
